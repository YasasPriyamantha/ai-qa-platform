/**
 * Unit tests for the generate command and candidate generator (Task Q4).
 *
 * Plans are written directly as files; no AI. The TypeScript check runs the
 * installed tsc. Everything is written to os.tmpdir().
 */

import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { executeGenerateCommand } from '../../../src/cli/generate-command.js';

type Target = { role: string; name: string } | null;
const step = (action: string, target: Target, value: string | null = null, assertion: string | null = null, locatorSource: string | null = target ? 'evidence' : null) =>
  ({ action, target, value, assertion, locatorSource });
const tb = (name: string): Target => ({ role: 'textbox', name });

const scenario = (n: number, extra: object = {}) => ({
  scenarioId: `SCN-${String(n).padStart(4, '0')}`, title: `Scenario ${n}`, requirementIds: ['REQ-001'], requirementVersions: { 'REQ-001': 2 },
  categories: ['functional'], priority: 'high', risk: 'medium', role: 'standard_user', preconditions: [], testData: [],
  steps: [step('goto', null, '/'), step('expect', null, 'Saved', 'text')],
  expectedResults: [{ requirementId: 'REQ-001', quote: 'The message `Saved` is shown.' }],
  questions: [], status: 'draft', ...extra,
});

/** One scenario using every action and assertion type. */
const EVERY_STEP = scenario(1, {
  title: 'Every action',
  steps: [
    step('goto', null, '/'),
    step('fill', tb('Username'), '{{credential:standard_user.username}}'),
    step('fill', tb('Password'), 'wrong_password'),
    step('select', { role: 'combobox', name: 'Sort' }, 'Name (A to Z)'),
    step('click', { role: 'button', name: 'Login' }, null, null, 'summary'),
    step('press', tb('Password'), 'Enter'),
    step('press', null, 'Tab'),
    step('expect', null, '/inventory.html', 'url'),
    step('expect', { role: 'heading', name: 'Products' }, null, 'visible', 'summary'),
    step('expect', null, "Epic sadface: it's no match", 'text'),
  ],
  expectedResults: [
    { requirementId: 'REQ-001', quote: 'taken to `https://www.example.com/inventory.html` and the heading `Products` is shown.' },
    { requirementId: 'REQ-001', quote: "Wrong password: the message `Epic sadface: it's no match` is shown." },
  ],
});

const EXPECTED_FILE = `// Candidate test generated by the AI QA platform (DEC-041). Not approved; regenerate instead of editing.
// Scenario: SCN-0001
// Requirements: REQ-001 (version 2)
// Plan: plan-test
// Explorations: exp-1

import { test, expect } from '@playwright/test';

/** A role credential from the environment; fails clearly when it is not set. */
function credential(name: string, value: string | undefined): string {
  if (!value) throw new Error(\`Environment variable \${name} is not set\`);
  return value;
}

test('SCN-0001: Every action', async ({ page }) => {
  // Expected (REQ-001): taken to https://www.example.com/inventory.html and the heading Products is shown.
  // Expected (REQ-001): Wrong password: the message Epic sadface: it's no match is shown.
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill(credential('DEMO_USER', process.env.DEMO_USER));
  await page.getByRole('textbox', { name: 'Password', exact: true }).fill('wrong_password');
  await page.getByRole('combobox', { name: 'Sort', exact: true }).selectOption('Name (A to Z)');
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.getByRole('textbox', { name: 'Password', exact: true }).press('Enter');
  await page.keyboard.press('Tab');
  await expect(page).toHaveURL('https://www.example.com/inventory.html');
  await expect(page.getByRole('heading', { name: 'Products', exact: true })).toBeVisible();
  await expect(page.getByText('Epic sadface: it\\'s no match', { exact: true })).toBeVisible();
});
`;

let root: string;
let workspace: string;
let configPath: string;
let logs: string;
let errors: string;

const candidates = () => join(workspace, 'tests', 'candidates');
const readPlan = () => JSON.parse(readFileSync(join(workspace, 'specs', 'candidates', 'plan-test.json'), 'utf-8'));

function writePlan(scenarios: object[]): void {
  mkdirSync(join(workspace, 'specs', 'candidates'), { recursive: true });
  writeFileSync(join(workspace, 'specs', 'candidates', 'plan-test.json'), JSON.stringify({
    schemaVersion: 1, planId: 'plan-test', projectId: 'demo', status: 'draft', createdAt: '2026-11-27T00:00:00.000Z',
    requirementIds: ['REQ-001'], excluded: [], explorationIds: ['exp-1'], provider: { providerId: 'openai', modelId: 'test' },
    limits: { maxScenarios: 20, maxAiRequests: 1 }, usage: { aiRequests: 1, inputTokens: 1, outputTokens: 1 },
    stopReason: 'completed', error: null, scenarios, rejected: [], notCovered: [], conflicts: [], questions: [],
  }));
}

const generate = (replace = false) => executeGenerateCommand({ configPath, planId: 'plan-test', replace, rootDir: root });
/** Skip reasons printed for one scenario. */
const skipLine = (id: string) => logs.split('\n').find((l) => l.includes(`Skipped:    ${id}:`)) ?? '';

beforeEach(() => {
  root = join(tmpdir(), `qa-generate-${Date.now()}-${Math.random().toString(36).slice(2)}`);
  workspace = join(root, 'project');
  mkdirSync(join(workspace, 'tests', 'approved'), { recursive: true });
  writeFileSync(join(workspace, 'tests', 'approved', 'smoke.spec.ts'), '// approved\n');
  writeFileSync(join(root, '.env'), 'DEMO_USER=demo_user\nDEMO_PASSWORD=s3cret-sentinel\n');
  configPath = join(workspace, 'project.config.json');
  writeFileSync(configPath, JSON.stringify({
    projectId: 'demo', name: 'Demo', baseUrl: 'https://www.example.com/', environment: 'demo',
    allowedDomains: ['www.example.com'], testDirectory: 'tests/approved', artifactDirectory: 'artifacts',
    roles: [{ roleId: 'standard_user', name: 'Standard user', credentials: { username: 'DEMO_USER', password: 'DEMO_PASSWORD' } }],
  }));
  mkdirSync(join(workspace, 'requirements'), { recursive: true });
  writeFileSync(join(workspace, 'requirements', 'registry.json'), JSON.stringify({
    schemaVersion: '1.0', updatedAt: new Date().toISOString(), requirements: {
      'REQ-001': {
        projectId: 'demo', requirementId: 'REQ-001', status: 'active', priority: 'high', title: 'Login',
        description: 'A user logs in; products can be sorted by `Name (A to Z)`. Test texts: ref=e12, css=.x, nth(2), waitForTimeout, test.only, https://evil.example.org/, s3cret-sentinel.',
        expectedResult: 'The message `Saved` is shown. After logging in the user is taken to `https://www.example.com/inventory.html` and the heading `Products` is shown.',
        negativeCases: [{ condition: 'Wrong password', expectedOutcome: 'logging in with the password `wrong_password` is prevented: the message `Epic sadface: it\'s no match` is shown.' }],
      },
    },
  }));
  logs = '';
  errors = '';
  vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => { logs += args.join(' ') + '\n'; });
  vi.spyOn(console, 'error').mockImplementation((...args: unknown[]) => { errors += args.join(' ') + '\n'; });
});

afterEach(() => {
  vi.restoreAllMocks();
  rmSync(root, { recursive: true, force: true });
});

// The TypeScript check starts tsc as a separate process, which can exceed the 5 s default when the full suite runs in parallel.
describe('generate', { timeout: 30_000 }, () => {
  it('renders every action and assertion type with the fixed templates, and the same input gives identical output', () => {
    writePlan([EVERY_STEP]);
    expect(generate()).toBe(0);
    const file = join(candidates(), 'SCN-0001.spec.ts');
    expect(readFileSync(file, 'utf-8')).toBe(EXPECTED_FILE);

    expect(generate(true)).toBe(0);
    expect(readFileSync(file, 'utf-8')).toBe(EXPECTED_FILE);
    expect(readPlan()).toMatchObject({ status: 'generated', scenarios: [{ scenarioId: 'SCN-0001', candidateFile: 'tests/candidates/SCN-0001.spec.ts' }] });
  });

  it('rejects each forbidden pattern and writes nothing for those scenarios', () => {
    const fill = (n: number, value: string) => scenario(n, { steps: [step('goto', null, '/'), step('fill', tb('Search'), value), step('expect', null, 'Saved', 'text')] });
    writePlan([
      fill(1, 'ref=e12'), fill(2, 'css=.x'), fill(3, 'nth(2)'), fill(4, 'waitForTimeout'), fill(5, 'test.only'),
      fill(6, 'https://evil.example.org/'), fill(7, 's3cret-sentinel'),
      scenario(8, { steps: [step('goto', null, 'https://evil.example.org/'), step('expect', null, 'Saved', 'text')] }),
    ]);
    expect(generate()).toBe(1);
    expect(existsSync(candidates()) ? readdirSync(candidates()) : []).toEqual([]);
    expect(skipLine('SCN-0001')).toContain('forbidden pattern: MCP reference (ref=)');
    expect(skipLine('SCN-0002')).toContain('forbidden pattern: CSS or XPath selector');
    expect(skipLine('SCN-0003')).toContain('forbidden pattern: nth(');
    expect(skipLine('SCN-0004')).toContain('forbidden pattern: waitForTimeout');
    expect(skipLine('SCN-0005')).toContain('forbidden pattern: test.only');
    expect(skipLine('SCN-0006')).toContain('forbidden pattern: absolute URL https://evil.example.org/');
    expect(skipLine('SCN-0007')).toContain('forbidden pattern: literal value of credential DEMO_PASSWORD');
    expect(skipLine('SCN-0008')).toContain('step 1: goto https://evil.example.org/');
    expect(logs).not.toMatch(/s3cret-sentinel/);
    expect(readPlan().status).toBe('draft');
  });

  it('skips scenarios that are not observed, not traced to quotes or requirements, or fail the TypeScript check', () => {
    const steps = (...extra: object[]) => [step('goto', null, '/'), ...extra, step('expect', null, 'Saved', 'text')];
    writePlan([
      scenario(1),
      scenario(2, { steps: steps(step('click', { role: 'button', name: 'Ghost' }, null, null, 'needs-observation')) }),
      scenario(3, { steps: steps(step('expect', null, 'Welcome back', 'text')) }),
      scenario(4, { steps: steps(step('fill', tb('Search'), 'invented value')) }),
      scenario(5, { steps: steps(step('fill', tb('Username'), '{{credential:standard_user.pin}}')) }),
      scenario(6, { steps: steps(step('fill', tb('Username'), 'x{{credential:standard_user.username}}')) }),
      scenario(7, { steps: [step('goto', null, '/')] }),
      scenario(8, { steps: steps(step('click', { role: 'bogusrole', name: 'Login' })) }),
    ]);
    expect(generate()).toBe(0);
    expect(readdirSync(candidates())).toEqual(['SCN-0001.spec.ts']);
    expect(skipLine('SCN-0002')).toContain('step 2: locator button "Ghost" needs observation');
    expect(skipLine('SCN-0003')).toContain('step 2: expected "Welcome back" is not in an expected-result quote');
    expect(skipLine('SCN-0004')).toContain('step 2: value "invented value" is not in the text of REQ-001');
    expect(skipLine('SCN-0005')).toContain('step 2: unknown credential {{credential:standard_user.pin}}');
    expect(skipLine('SCN-0006')).toContain('step 2: credential placeholder mixed with other text');
    expect(skipLine('SCN-0007')).toContain('expected result "The message Saved is shown." has no expect step');
    expect(skipLine('SCN-0008')).toMatch(/TypeScript line \d+: TS2345: Argument of type '"bogusrole"'/);
  });

  it('never overwrites a candidate without --replace, never touches the approved folder, and enforces the file limit', () => {
    writePlan(Array.from({ length: 21 }, (_, i) => scenario(i + 1)));
    expect(generate()).toBe(0);
    expect(readdirSync(candidates())).toHaveLength(20);
    expect(skipLine('SCN-0021')).toContain('file limit of 20 per run reached');

    const first = join(candidates(), 'SCN-0001.spec.ts');
    writeFileSync(first, '// edited by a person\n');
    logs = '';
    expect(generate()).toBe(0);
    expect(readFileSync(first, 'utf-8')).toBe('// edited by a person\n');
    expect(skipLine('SCN-0001')).toContain('tests/candidates/SCN-0001.spec.ts exists; use --replace to overwrite it');
    expect(readdirSync(join(workspace, 'tests', 'approved'))).toEqual(['smoke.spec.ts']);
    expect(readFileSync(join(workspace, 'tests', 'approved', 'smoke.spec.ts'), 'utf-8')).toBe('// approved\n');

    expect(generate(true)).toBe(0);
    expect(readFileSync(first, 'utf-8')).toContain('// Scenario: SCN-0001');

    // A project whose approved test folder is the candidate folder is refused before anything is written.
    writeFileSync(configPath, readFileSync(configPath, 'utf-8').replace('"tests/approved"', '"tests/candidates"'));
    expect(generate(true)).toBe(1);
    expect(errors).toMatch(/overlaps the approved test folder/);
  });
});
