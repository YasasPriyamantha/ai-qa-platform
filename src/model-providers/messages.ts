/**
 * Provider-neutral conversation message types.
 *
 * Implements the typed conversation message union from Task 3.2 requirement 4.
 *
 * Key principles:
 * - Messages form a discriminated union by 'role' field
 * - Tool calls use stable call IDs for correlation
 * - Tool results link back to their originating call
 * - Continuation metadata preserves conversation state
 * - Content supports text and allows extension for images
 */

/**
 * Message roles in a conversation.
 */
export type MessageRole = 'system' | 'user' | 'assistant' | 'tool';

// ============================================================================
// Content Types
// ============================================================================

/**
 * Text content in a message.
 */
export interface TextContent {
  readonly type: 'text';
  readonly text: string;
}

/**
 * Image content in a message (for vision models).
 * Base64 encoded data with media type.
 */
export interface ImageContent {
  readonly type: 'image';
  readonly mediaType: 'image/png' | 'image/jpeg' | 'image/gif' | 'image/webp';
  /**
   * Base64-encoded image data.
   * Do not log or persist this in reports.
   */
  readonly data: string;
}

/**
 * Image URL reference.
 * Some providers support URL-based images.
 */
export interface ImageUrlContent {
  readonly type: 'image_url';
  readonly url: string;
}

/**
 * Content item union.
 * Extendable for future content types (audio, video, etc.).
 */
export type ContentItem = TextContent | ImageContent | ImageUrlContent;

/**
 * Message content can be a simple string or array of content items.
 */
export type MessageContent = string | readonly ContentItem[];

// ============================================================================
// System/Developer Message
// ============================================================================

/**
 * System or developer instruction message.
 *
 * Used for:
 * - OpenAI: system message or developer message in Responses API
 * - Anthropic: system parameter or system content block
 * - Gemini: system_instruction
 *
 * Not all providers distinguish between system and developer roles.
 * Adapters handle the mapping.
 */
export interface SystemMessage {
  readonly role: 'system';

  /**
   * System/developer instruction content.
   */
  readonly content: string;

  /**
   * Optional name for multi-system-message scenarios.
   */
  readonly name?: string;

  /**
   * Cache control hint for providers that support prompt caching.
   * Adapters ignore if not supported.
   */
  readonly cacheControl?: CacheControlHint;
}

// ============================================================================
// User Message
// ============================================================================

/**
 * User message in a conversation.
 */
export interface UserMessage {
  readonly role: 'user';

  /**
   * User message content.
   * String for text-only, array for multi-modal content.
   */
  readonly content: MessageContent;

  /**
   * Optional name identifying the user in multi-user scenarios.
   */
  readonly name?: string;
}

// ============================================================================
// Assistant Message
// ============================================================================

/**
 * Tool call request from the assistant.
 *
 * Contains the information needed to execute a tool and correlate the result.
 */
export interface ToolCall {
  /**
   * Stable identifier for this tool call.
   * Used to correlate tool results back to the call.
   * Generated by the provider; must be preserved exactly.
   */
  readonly id: string;

  /**
   * Name of the tool being called.
   * Must match a tool name in the request's tool definitions.
   */
  readonly name: string;

  /**
   * JSON-encoded arguments for the tool.
   * This is untrusted input from the model; must be validated before use.
   */
  readonly arguments: string;
}

/**
 * Text response from the assistant.
 */
export interface AssistantTextContent {
  readonly type: 'text';
  readonly text: string;
}

/**
 * Tool call content block in an assistant message.
 */
export interface AssistantToolCallContent {
  readonly type: 'tool_call';
  readonly toolCall: ToolCall;
}

/**
 * Refusal content - assistant declined to respond.
 */
export interface AssistantRefusalContent {
  readonly type: 'refusal';
  readonly refusal: string;
}

/**
 * Assistant content item union.
 */
export type AssistantContentItem =
  | AssistantTextContent
  | AssistantToolCallContent
  | AssistantRefusalContent;

/**
 * Assistant message in a conversation.
 *
 * May contain:
 * - Text response
 * - Tool call requests
 * - Refusal
 * - Or a combination in multi-part responses
 */
export interface AssistantMessage {
  readonly role: 'assistant';

  /**
   * Assistant response content.
   * String for simple text, array for multi-part responses including tool calls.
   */
  readonly content: string | readonly AssistantContentItem[];

  /**
   * Convenience accessor for tool calls in this message.
   * Extracted from content blocks of type 'tool_call'.
   */
  readonly toolCalls?: readonly ToolCall[];

  /**
   * Continuation metadata for preserving conversation state.
   * This is an opaque reference; actual state is in ContinuationState.
   */
  readonly continuationRef?: string;
}

// ============================================================================
// Tool Result Message
// ============================================================================

/**
 * Tool result content item.
 *
 * Per Task 3.2 additional context item 4: Tool results support
 * typed content collections with at least text and allowing image.
 */
export type ToolResultContentItem = TextContent | ImageContent;

/**
 * Tool result message.
 *
 * Sent after executing a tool call to provide the result back to the model.
 */
export interface ToolResultMessage {
  readonly role: 'tool';

  /**
   * ID of the tool call this result responds to.
   * Must match the id from the corresponding ToolCall.
   */
  readonly toolCallId: string;

  /**
   * Name of the tool that was called.
   * Per Task 3.2: Include tool name for correlation verification.
   */
  readonly toolName: string;

  /**
   * Result content from the tool.
   * String for simple text results, array for structured/multi-part results.
   */
  readonly content: string | readonly ToolResultContentItem[];

  /**
   * Whether this result represents an error from the tool.
   * Per Task 3.2 additional context item 4: Explicit error indicator.
   */
  readonly isError?: boolean;
}

// ============================================================================
// Message Union
// ============================================================================

/**
 * Conversation message union.
 * Discriminated by the 'role' field.
 */
export type ConversationMessage =
  | SystemMessage
  | UserMessage
  | AssistantMessage
  | ToolResultMessage;

// ============================================================================
// Cache Control
// ============================================================================

/**
 * Cache control hint for prompt caching (Anthropic, potentially others).
 */
export interface CacheControlHint {
  /**
   * Ephemeral content should not be cached.
   */
  readonly type: 'ephemeral';
}

// ============================================================================
// Message Helpers
// ============================================================================

/**
 * Type guard for SystemMessage.
 */
export function isSystemMessage(msg: ConversationMessage): msg is SystemMessage {
  return msg.role === 'system';
}

/**
 * Type guard for UserMessage.
 */
export function isUserMessage(msg: ConversationMessage): msg is UserMessage {
  return msg.role === 'user';
}

/**
 * Type guard for AssistantMessage.
 */
export function isAssistantMessage(msg: ConversationMessage): msg is AssistantMessage {
  return msg.role === 'assistant';
}

/**
 * Type guard for ToolResultMessage.
 */
export function isToolResultMessage(msg: ConversationMessage): msg is ToolResultMessage {
  return msg.role === 'tool';
}

/**
 * Extract tool calls from an assistant message.
 */
export function extractToolCalls(msg: AssistantMessage): ToolCall[] {
  // Check explicit toolCalls field first
  if (msg.toolCalls && msg.toolCalls.length > 0) {
    return [...msg.toolCalls];
  }

  // Extract from content blocks
  if (typeof msg.content === 'string') {
    return [];
  }

  const toolCalls: ToolCall[] = [];
  for (const item of msg.content) {
    if (item.type === 'tool_call') {
      toolCalls.push(item.toolCall);
    }
  }
  return toolCalls;
}

/**
 * Check if an assistant message requests tool calls.
 */
export function hasToolCalls(msg: AssistantMessage): boolean {
  if (msg.toolCalls && msg.toolCalls.length > 0) {
    return true;
  }

  if (typeof msg.content === 'string') {
    return false;
  }

  return msg.content.some((item) => item.type === 'tool_call');
}

/**
 * Get text content from an assistant message.
 */
export function getAssistantText(msg: AssistantMessage): string {
  if (typeof msg.content === 'string') {
    return msg.content;
  }

  const textParts: string[] = [];
  for (const item of msg.content) {
    if (item.type === 'text') {
      textParts.push(item.text);
    }
  }
  return textParts.join('');
}

/**
 * Check if an assistant message contains a refusal.
 */
export function hasRefusal(msg: AssistantMessage): boolean {
  if (typeof msg.content === 'string') {
    return false;
  }

  return msg.content.some((item) => item.type === 'refusal');
}

/**
 * Get refusal reason from an assistant message.
 */
export function getRefusalReason(msg: AssistantMessage): string | undefined {
  if (typeof msg.content === 'string') {
    return undefined;
  }

  for (const item of msg.content) {
    if (item.type === 'refusal') {
      return item.refusal;
    }
  }
  return undefined;
}

/**
 * Create a simple text user message.
 */
export function userMessage(text: string, name?: string): UserMessage {
  return {
    role: 'user',
    content: text,
    ...(name ? { name } : {}),
  };
}

/**
 * Create a system message.
 */
export function systemMessage(content: string, name?: string): SystemMessage {
  return {
    role: 'system',
    content,
    ...(name ? { name } : {}),
  };
}

/**
 * Create a simple text assistant message.
 */
export function assistantTextMessage(text: string): AssistantMessage {
  return {
    role: 'assistant',
    content: text,
  };
}

/**
 * Create a tool result message.
 */
export function toolResultMessage(
  toolCallId: string,
  toolName: string,
  content: string | readonly ToolResultContentItem[],
  isError?: boolean
): ToolResultMessage {
  return {
    role: 'tool',
    toolCallId,
    toolName,
    content,
    ...(isError !== undefined ? { isError } : {}),
  };
}

/**
 * Create an assistant message with tool calls.
 */
export function assistantToolCallMessage(
  toolCalls: readonly ToolCall[],
  text?: string
): AssistantMessage {
  const content: AssistantContentItem[] = [];

  if (text) {
    content.push({ type: 'text', text });
  }

  for (const toolCall of toolCalls) {
    content.push({ type: 'tool_call', toolCall });
  }

  return {
    role: 'assistant',
    content,
    toolCalls,
  };
}
